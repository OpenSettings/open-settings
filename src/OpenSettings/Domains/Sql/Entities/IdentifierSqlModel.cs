using System;
using System.Collections.Generic;

namespace OpenSettings.Domains.Sql.Entities
{
    /// <summary>
    /// Represents an identifier entity.
    /// </summary>
    public class IdentifierSqlModel : EntityBase<int>, IOrderedEntity
    {
        /// <summary>
        /// The name of the identifier.
        /// </summary>
        public string Name { get; set; }

        /// <summary>
        /// The lowercase version of the <see cref="Name"/>, typically used for case-insensitive comparisons.
        /// </summary>
        public string NameLowercase { get; set; }

        /// <summary>
        /// An url friendly version of the <see cref="Name"/>, generated by trimming, converting to lowercase,  
        /// and replacing spaces or special characters with hyphens (using <see cref="Extensions.InternalExtensions.ToSlug"/> extension method).
        /// </summary>
        public string Slug { get; set; }

        /// <summary>
        /// The sort order of this identifier in a list.
        /// </summary>
        public int SortOrder { get; set; }

        /// <summary>
        /// A concurrency token used for tracking changes.  
        /// Helps prevent conflicts during concurrent updates.
        /// </summary>
        public byte[] RowVersion { get; set; } = Array.Empty<byte>();

        /// <summary>
        /// The id of the user who created this identifier.
        /// </summary>
        public Guid? CreatedById { get; set; }

        /// <summary>
        /// The user who created this identifier.
        /// </summary>
        public virtual UserSqlModel CreatedBy { get; set; }

        /// <summary>
        /// The id of the user who last updated this identifier.
        /// </summary>
        public Guid? UpdatedById { get; set; }

        /// <summary>
        /// The user who last updated this identifier.
        /// </summary>
        public virtual UserSqlModel UpdatedBy { get; set; }

        /// <summary>
        /// A collection of app-identifier mappings.
        /// </summary>
        public virtual ICollection<AppIdentifierMappingSqlModel> AppIdentifierMappings { get; set; } = new List<AppIdentifierMappingSqlModel>();
    }
}